PACKS = {TAFFY: TAFFY_PACK}


def normalize(style, persona=""):
    """未知或缺失的风格按人设内容推断，保证老配置平滑升级。"""
    if style in VALID:
        return style
    if persona and persona != DEFAULT_PERSONA:
        return CUSTOM
    return DEFAULT


def bundle(style):
    return PACKS.get(style, {})


def effective_persona(ai_cfg):
    ai_cfg = ai_cfg or {}
    style = normalize(ai_cfg.get("style"), ai_cfg.get("persona", ""))
    if style == TAFFY:
        return TAFFY_PACK["persona"]
    if style == CUSTOM:
        return ai_cfg.get("persona") or DEFAULT_PERSONA
    return DEFAULT_PERSONA


def game_persona(ai_cfg):
    """游戏决策需要同一套口吻，但不带聊天专用的本地话术。"""
    ai_cfg = ai_cfg or {}
    style = normalize(ai_cfg.get("style"), ai_cfg.get("persona", ""))
    persona = effective_persona(ai_cfg)
    rules = PACKS.get(style, {}).get("game_rules")
    return persona + ("\n" + rules if rules else "")


def resolve(style, key, fallback):
    return PACKS.get(style, {}).get(key) or fallback


def resolve_config(style, key, configured, builtin):
    """用户改过的文案优先；仍是出厂默认时才跟随风格切换。"""
    if configured and configured != builtin:
        return configured
    return PACKS.get(style, {}).get(key) or builtin


def resolve_event(style, event_type, configured, builtin):
    if configured and configured != builtin:
        return configured
    return PACKS.get(style, {}).get("event_templates", {}).get(event_type) or builtin


def sanitize_reply(text):
    """清掉模型漏出的猫叫，并把旧粉丝名统一成观众姥爷。"""
    return (text.replace("喵", "")
            .replace("雏草姬", "观众姥爷").replace("除草剂", "观众姥爷").replace("小鲸子", "观众姥爷"))


