@dataclass(frozen=True)
class ViewerCue:
    kind: str
    instruction: str
    fallbacks: tuple[str, ...]
    emotions: tuple[str, ...]
    private: bool = False

    def prompt(self):
        return ("\n【本条留言的接话方向】" + self.instruction
                + "这是轻量文本线索，以观众原话为准，不推断未说出的经历，不照读这些说明。")

    def emotion(self, names):
        return next((name for name in self.emotions if name in names), "")


