def enabled(cfg):
    return bool(cfg.get("interaction", {}).get("emotional_value", True))


def viewer_cue(text):
    # 仅作保守接话提示：不把否定、术语解释和其他人的情绪当成本人的情绪。
    text = str(text or "")[:300].strip()
    text = re.sub(r"(?:没有|没|不)(?:那么|太|再)?(?:难过|伤心|焦虑|委屈|孤单|想哭|累|困)(?:了)?", "", text)
    text = re.sub(r"(?:不需要|不用|不要|别)(?:再)?(?:安慰|鼓励)(?:我|一下)?|不是我(?:的)?生日", "", text)
    text = re.sub(r"(?:没有|没|尚未|未能)(?:上岸了?|面试通过|考试过了|升职了?|涨薪了?|获奖了?)", "", text, flags=re.I)
    for kind, pattern in _PATTERNS:
        if pattern.search(text):
            return CUES[kind]
    return None
